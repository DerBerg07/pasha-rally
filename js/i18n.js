  const LANG_KEY = 'animal-rally-lang';
  let saved = null;
  try { saved = localStorage.getItem(LANG_KEY); } catch (e) { /* storage blocked */ }
  AR.lang = saved === 'en' || saved === 'uk' ? saved : (/^en/i.test((typeof navigator !== 'undefined' && navigator.language) || '') ? 'en' : 'uk');
  AR.setLang = l => {
    AR.lang = l === 'en' ? 'en' : 'uk';
    try { localStorage.setItem(LANG_KEY, AR.lang); } catch (e) { /* storage blocked */ }
    if (typeof document !== 'undefined') document.documentElement.lang = AR.lang;
  };
  if (typeof document !== 'undefined') document.documentElement.lang = AR.lang;

  /* localized data field: tx(card, 'name') */
  AR.tx = (obj, field) => (obj ? (AR.lang === 'en' && obj[field + '_en'] !== undefined ? obj[field + '_en'] : obj[field]) : '');
  AR.t = (key, ...args) => {
    const v = AR.STR[AR.lang][key] !== undefined ? AR.STR[AR.lang][key] : AR.STR.uk[key];
    return typeof v === 'function' ? v(...args) : v;
  };
  AR.esc = esc;

  /* Render a message ({k, a}) into HTML in the current language. `game` resolves player references. */
  AR.fmt = function fmt(m, game) {
    if (m === null || m === undefined) return '';
    if (typeof m === 'string') return m;
    if (typeof m === 'number') return String(m);
    if (!m.k) return '';
    const args = (m.a || []).map(a => {
      if (a === null || a === undefined) return null;
      if (typeof a === 'number' || typeof a === 'boolean') return a;
      if (typeof a === 'string') return esc(a);
      if (a.k) return fmt(a, game);
      if (a.p !== undefined) {
        const p = game && game.players[a.p];
        return p ? `<b class="who" style="--pc:${p.color}">${esc(p.name)}</b>` : '?';
      }
      if (a.c) return esc(AR.tx(AR.CARDS[a.c], 'name'));
      if (a.r) return esc(AR.tx(AR.racer(a.r), 'name'));
      if (a.tile !== undefined) {
        const c = game && game.track.cells[a.tile];
        if (!c) return '';
        return esc(AR.tx(c.type === 'tp' ? AR.TILES.tp : (AR.TILES[c.type] || AR.TILES.plain), 'name'));
      }
      return '';
    });
    return AR.t(m.k, ...args);
  };
  AR.plain = html => String(html).replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'");
